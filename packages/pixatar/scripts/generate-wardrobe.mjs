/**
 * Bakes the pinned Pixel Agents wardrobe into src/generated/wardrobe.ts: its manifest
 * (art/wardrobe.json) and every art PNG, decoded here to RGBA and stored as one deflated
 * blob. The package then needs no PNG decoder, no canvas and no file access at runtime, so
 * it renders the same in Node and in the browser.
 *
 * Nothing about the wardrobe is hand-kept: a vendor bump that adds parts (a seasonal theme,
 * say) reaches the package by re-running this, which build, test and typecheck all do.
 */

import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

import { zlibSync } from 'fflate';
import { PNG } from 'pngjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const VENDOR = path.resolve(HERE, '../../../vendor/pixel-agents');
const ART = path.join(VENDOR, 'webview-ui/src/characters/art');
const OUT = path.resolve(HERE, '../src/generated/wardrobe.ts');

if (!fs.existsSync(path.join(ART, 'wardrobe.json'))) {
  console.error(`No wardrobe at ${ART}: run \`git submodule update --init\` first.`);
  process.exit(1);
}

/** Every PNG under art/, as [art path without '.png', absolute file], sorted so the blob is stable. */
function pngs(dir, prefix = '') {
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .flatMap((entry) => {
      const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
      if (entry.isDirectory()) return pngs(path.join(dir, entry.name), rel);
      return entry.name.endsWith('.png') ? [[rel.slice(0, -4), path.join(dir, entry.name)]] : [];
    })
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
}

const files = pngs(ART);
const art = [];
const chunks = [];
for (const [artPath, file] of files) {
  const png = PNG.sync.read(fs.readFileSync(file));
  art.push([artPath, png.width, png.height]);
  chunks.push(new Uint8Array(png.data.buffer, png.data.byteOffset, png.data.byteLength));
}
const raw = new Uint8Array(chunks.reduce((n, c) => n + c.length, 0));
let at = 0;
for (const c of chunks) {
  raw.set(c, at);
  at += c.length;
}
const blob = Buffer.from(zlibSync(raw, { level: 9 })).toString('base64');

const manifest = JSON.parse(fs.readFileSync(path.join(ART, 'wardrobe.json'), 'utf8'));
// The repo's committed pin stamp (tools/vendor-commit.mjs), not `git rev-parse`: a Docker
// build has the vendor sources but no git to ask, and CI's vendor:commit:check keeps the
// stamp equal to the submodule pin.
const commit = fs.readFileSync(`${VENDOR}.commit`, 'utf8').trim();
const { version } = JSON.parse(fs.readFileSync(path.join(VENDOR, 'package.json'), 'utf8'));

const source = `// Generated by scripts/generate-wardrobe.mjs from vendor/pixel-agents. Do not edit.

/** The Pixel Agents checkout this wardrobe was baked from. */
export const VENDOR = ${JSON.stringify({ version, commit })} as const;

/** art/wardrobe.json, verbatim. */
export const MANIFEST: unknown = ${JSON.stringify(manifest)};

/** Each art sheet: [art path, width, height], in the order PIXELS holds them. */
export const ART: readonly (readonly [string, number, number])[] = ${JSON.stringify(art)};

/** Every sheet's RGBA pixels, back to back, zlib-deflated, base64. */
export const PIXELS = ${JSON.stringify(blob)};
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, source);
console.log(
  `wardrobe: ${art.length} sheets, ${(blob.length / 1024).toFixed(0)} KiB baked from pixel-agents ${version} (${commit.slice(0, 7)})`,
);
